const origin = 'http://127.0.0.1:4173';
const T0 = Date.now();
const fails = [];
const seen = new Set();
const p = await context.newPage();
p.on('response', (r) => {
  const s = r.status();
  if (s < 400) return;
  fails.push({ status: s, url: r.url(), atMs: Date.now() - T0 });
});
p.on('pageerror', (e) => console.log('PAGEERR ' + String(e.message).slice(0, 120)));
await p.route((u) => new URL(u).pathname === '/ready-plate', (r) => r.fulfill({ status: 200, contentType: 'text/html', body: '' }));
await p.goto(origin + '/', { waitUntil: 'load', timeout: 90000 });
console.log('STEP kernel-load t=' + (Date.now() - T0) + 'ms');
await new Promise((r) => setTimeout(r, 30000));
const stood = await p.evaluate(() => ({ stood: document.documentElement.hasAttribute('data-spawn-stood'), shown: document.documentElement.classList.contains('spawn-world-shown') })).catch((e) => ({ error: String(e.message).slice(0, 80) }));
console.log('STEP settled t=' + (Date.now() - T0) + 'ms ' + JSON.stringify(stood));
const ids = [...new Map(fails.map((f) => [f.url, f])).values()];
const { default: _unused } = { default: null };
console.log('FAILS count=' + fails.length + ' distinct=' + ids.length);
console.log('FAILS_JSON ' + JSON.stringify(ids));
await p.close();
