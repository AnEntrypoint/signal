const fs = require('fs');
const [liveFile, witFile, outFile] = process.argv.slice(2);
const live = JSON.parse(fs.readFileSync(liveFile, 'utf8')).ev || [];
const wit = JSON.parse(fs.readFileSync(witFile, 'utf8')).ev || [];
const at = (e) => (e.ms !== undefined ? e.ms : e.t);
const norm = (s) => String(s).replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f-]{8,}/g, '<uuid>').replace(/[0-9a-f]{8}-[0-9a-f]{8,}/g, '<id>').replace(/spawn-page=[0-9a-f]+/g, 'spawn-page=<p>').replace(/\/[0-9a-f]{32,}/g, '/<hash>').replace(/[0-9a-f]{16,}/g, '<hex>');
const path = (u) => { try { const x = new URL(u); return norm(x.pathname.replace(/^\/signal\//, '') + x.search.slice(0, 80)); } catch (e) { return norm(String(u).slice(0, 120)); } };
const interesting = (e) => ['req', 'nav', 'attach', 'detach', 'fail', 'console', 'pageerror'].includes(e.k);
const line = (side, e) => {
  const what = e.k === 'req' ? 'REQ ' + path(e.u) + ' [' + e.type + ']' : e.k === 'fail' ? 'FAIL ' + path(e.u) + ' ' + e.err : (e.k === 'nav' || e.k === 'attach' || e.k === 'detach') ? e.k.toUpperCase() + ' ' + path(e.f) : e.k === 'console' ? 'CONSOLE ' + norm(e.txt).slice(0, 150) : 'PAGEERROR ' + norm(e.txt).slice(0, 150);
  return [at(e) || 0, side + ' ' + String(at(e) || 0).padStart(7) + ' ' + what];
};
const firstSeen = (ev) => { const seen = new Set(); const out = []; for (const e of ev) if (e.k === 'req') { const p = path(e.u); if (!seen.has(p)) { seen.add(p); out.push(p); } } return out; };
const lf = firstSeen(live);
const wf = firstSeen(wit);
const ls = new Set(lf);
const ws = new Set(wf);
let idx = -1;
for (let i = 0; i < Math.min(lf.length, wf.length); i++) if (lf[i] !== wf[i]) { idx = i; break; }
const onlyWit = wf.filter((p) => !ls.has(p)).slice(0, 40);
const onlyLive = lf.filter((p) => !ws.has(p)).slice(0, 40);
const tl = [...live.filter(interesting).map((e) => line('L', e)), ...wit.filter(interesting).map((e) => line('W', e))].sort((a, b) => a[0] - b[0]).map((x) => x[1]);
const lines = [];
lines.push('FIRST_ORDER_DIFFERENCE index=' + idx + ' live=' + (lf[idx] || '-') + ' | witness=' + (wf[idx] || '-'));
lines.push('ONLY_IN_WITNESS (' + onlyWit.length + '):');
onlyWit.forEach((p) => lines.push('  W ' + p));
lines.push('ONLY_IN_LIVE (' + onlyLive.length + '):');
onlyLive.forEach((p) => lines.push('  L ' + p));
lines.push('TIMELINE (ms from page creation; L live, W witness; first 600 events):');
tl.slice(0, 6000).forEach((l) => lines.push(l));
fs.writeFileSync(outFile, lines.join('\n') + '\n');
console.log(lines.slice(0, 1).join('\n'), 'only_w', onlyWit.length, 'only_l', onlyLive.length);
