import { writeFileSync } from 'node:fs';
const [port, holderPid] = process.argv.slice(2);
const events = [];
const EXTRA_CATEGORIES = (process.env.HOLDER_EXTRA_CATEGORIES || '').split(',').filter(Boolean);
const HOLDER = Number(holderPid);
const out = { pid: HOLDER, mode: null, error: null, dumpGuid: null, dumpSuccess: false, requestedAtMs: null, completedAtMs: null, eventsSeen: 0, requestedEvents: 0, requestedShapes: {}, requestedEndArgKeys: null, dumpNames: {}, dumpEventIds: [], periodicSamples: 0, periodicProcessTotalsKeys: null, privateFootprintBytes: null, peakResidentSetBytes: null, endReplyAtMs: null, tracingCompleteAtMs: null, dumpReplyKeys: null, dataLossOccurred: null, bufferUsageSamples: 0, bufferUsageSeries: [], lastBufferUsage: null, matchedDump: false, residentSetBytes: null, partitionAlloc: null, topAllocators: [] };
const finish = () => { if (process.env.HOLDER_EVENTS_OUT) writeFileSync(process.env.HOLDER_EVENTS_OUT, JSON.stringify(events)); console.log('HOLDER_MEMDUMP ' + JSON.stringify(out)); process.exit(0); };
const GUARD_MS = Number(process.env.HOLDER_GUARD_MS || 40000);
const END_WAIT_MS = Number(process.env.HOLDER_END_WAIT_MS || 20000);
const onGuard = () => { out.error = 'timeout'; finish(); };
let guard = setTimeout(onGuard, GUARD_MS);
const rearm = (ms) => { clearTimeout(guard); guard = setTimeout(onGuard, ms); };
const sizeOf = (attrs, key) => (attrs && attrs[key] && attrs[key].units === 'bytes' ? parseInt(attrs[key].value, 16) : null);
const hexBytes = (v) => (typeof v === 'string' && /^[0-9a-f]+$/i.test(v) ? parseInt(v, 16) : null);
const summarize = (events) => {
  const dumps = events.filter((e) => e.ph === 'v' && e.pid === HOLDER && e.args && e.args.dumps);
  out.dumpEventIds = [...new Set(dumps.map((e) => String(e.id)))].slice(0, 10);
  out.dumpNames = dumps.reduce((acc, e) => ({ ...acc, [e.name]: (acc[e.name] || 0) + 1 }), {});
  const requested = events.filter((e) => e.pid === HOLDER && e.name === 'ProcessMemoryDump' && (e.ph === 'b' || e.ph === 'e') && e.args && e.args.dump_guid === out.dumpGuid);
  out.requestedShapes = requested.reduce((acc, e) => ({ ...acc, [e.ph + '|' + e.name]: (acc[e.ph + '|' + e.name] || 0) + 1 }), {});
  const requestedEnd = requested.filter((e) => e.ph === 'e');
  out.requestedEndArgKeys = requestedEnd.length ? Object.keys(requestedEnd[0].args) : null;
  out.requestedEvents = requested.length;
  const periodic = events.filter((e) => e.ph === 'v' && e.name === 'periodic_interval' && e.pid === HOLDER && e.args && e.args.dumps && e.args.dumps.process_totals);
  out.periodicSamples = periodic.length;
  const latest = periodic.reduce((best, e) => (best === null || e.ts > best.ts ? e : best), null);
  out.periodicProcessTotalsKeys = latest ? Object.keys(latest.args.dumps.process_totals) : null;
  out.privateFootprintBytes = latest ? hexBytes(latest.args.dumps.process_totals.private_footprint_bytes) : null;
  out.peakResidentSetBytes = latest ? hexBytes(latest.args.dumps.process_totals.peak_resident_set_size) : null;
  out.matchedDump = requested.length > 0;
  const pick = requestedEnd.filter((e) => e.args.dumps).pop();
  if (!pick) return;
  const allocators = pick.args.dumps.allocators || {};
  const procTotals = pick.args.dumps.process_totals || {};
  out.residentSetBytes = sizeOf(procTotals.attrs, 'resident_set_bytes');
  const rows = Object.entries(allocators).map(([name, a]) => ({ name, sizeBytes: sizeOf(a.attrs, 'size') })).filter((r) => r.sizeBytes !== null);
  const parts = rows.filter((r) => /^partition_alloc\/partitions\/[^/]+$/.test(r.name)).map((r) => ({ name: r.name.split('/')[2], sizeBytes: r.sizeBytes })).sort((a, b) => b.sizeBytes - a.sizeBytes);
  out.partitionAlloc = { totalBytes: parts.reduce((s, p) => s + p.sizeBytes, 0), partitions: parts };
  out.topAllocators = rows.filter((r) => r.name.split('/').length <= 3).sort((a, b) => b.sizeBytes - a.sizeBytes).slice(0, 20);
};
const run = async () => {
  const ver = await (await fetch('http://127.0.0.1:' + port + '/json/version')).json();
  const sock = new WebSocket(ver.webSocketDebuggerUrl);
  await new Promise((res, rej) => { sock.onopen = res; sock.onerror = () => rej(new Error('websocket failed')); });
  let seq = 0;
  const waiting = new Map();
  let complete = null;
  const completed = new Promise((res) => { complete = res; });
  sock.onmessage = (ev) => {
    const m = JSON.parse(String(ev.data));
    if (m.method === 'Tracing.bufferUsage') { const bu = m.params || {}; out.bufferUsageSamples += 1; const sample = { atMs: Date.now(), percentFull: bu.percentFull ?? null, eventCount: bu.eventCount ?? null }; out.bufferUsageSeries.push(sample); out.lastBufferUsage = sample; return; }
    if (m.method === 'Tracing.dataCollected') { events.push(...((m.params && m.params.value) || [])); return; }
    if (m.method === 'Tracing.tracingComplete') { out.tracingCompleteAtMs = Date.now(); out.dataLossOccurred = (m.params && m.params.dataLossOccurred) ?? null; complete(); return; }
    const w = waiting.get(m.id);
    if (!w) return;
    waiting.delete(m.id);
    if (m.error) w.reject(new Error(m.error.message)); else w.resolve(m.result);
  };
  const send = (method, params) => new Promise((resolve, reject) => { const id = ++seq; waiting.set(id, { resolve, reject }); sock.send(JSON.stringify({ id, method, params: params || {} })); });
  await send('Tracing.start', { traceConfig: { recordMode: 'recordUntilFull', includedCategories: ['-*', 'disabled-by-default-memory-infra', ...EXTRA_CATEGORIES] }, transferMode: 'ReportEvents', bufferUsageReportingInterval: 1000 });
  const NO_DUMP_HOLD_MS = 3000;
  out.mode = process.env.HOLDER_MODE === 'no-dump' ? 'no-dump' : 'dump';
  if (out.mode === 'no-dump') await new Promise((res) => setTimeout(res, NO_DUMP_HOLD_MS));
  out.requestedAtMs = out.mode === 'dump' ? Date.now() : null;
  const dump = out.mode === 'dump' ? await send('Tracing.requestMemoryDump', { deterministic: false, levelOfDetail: 'detailed' }) : {};
  out.completedAtMs = out.mode === 'dump' ? Date.now() : null;
  out.dumpGuid = dump.dumpGuid || null;
  out.dumpSuccess = dump.success === true;
  out.dumpReplyKeys = Object.keys(dump).sort();
  rearm(END_WAIT_MS);
  send('Tracing.end').then(() => { out.endReplyAtMs = Date.now(); }, () => {});
  await completed;
  out.eventsSeen = events.length;
  summarize(events);
  sock.close();
};
run().then(() => { clearTimeout(guard); finish(); }, (e) => { clearTimeout(guard); out.error = String(e.message).slice(0, 200); finish(); });
